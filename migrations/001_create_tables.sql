CREATE SEQUENCE IF NOT EXISTS assets_seq MAXVALUE 9223372036854775807;
CREATE SEQUENCE IF NOT EXISTS users_seq MAXVALUE 9223372036854775807;

CREATE TABLE IF NOT EXISTS assets (
    id NUMBER(19) PRIMARY KEY,
    name VARCHAR2(1000 CHAR) NOT NULL UNIQUE,
    unit_value BINARY_DOUBLE NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id NUMBER(19) PRIMARY KEY,
    username VARCHAR2(255 CHAR) NOT NULL UNIQUE,
    password_hash VARCHAR2(512 CHAR) NOT NULL
);
